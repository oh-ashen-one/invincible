// ------------------------------------------------------------------ pedestrian graph
// Corners of every grid junction (avenue x street): the four sidewalk corner points; sidewalk edges along the avenue / street
// sides between neighbouring junctions; crosswalk edges across each existing leg. Every point is checked against the browser
// layout (streetsAt): sidewalk points must be 'sidewalk', crosswalk samples must be asphalt ('avenue' / 'street' / 'intersection').
const WM = 1.0; // keep points this far inside the region
const nodes = R.nodes.filter((n) => n && n.av && n.st && n.i >= 0 && n.j >= 0);
const cornerKey = (n, sx, sz) => `${n.id}:${sx}:${sz}`;
const corners = new Map(); const P = [];
const isWalk = (x, z) => streetsAt(x, z).type === 'sidewalk';
const isRoad = (x, z) => { const t = streetsAt(x, z).type; return t === 'avenue' || t === 'street' || t === 'intersection'; };
for (const n of nodes) {
  for (const sx of [-1, 1]) for (const sz of [-1, 1]) {
    let ok = null;
    // walk outward from the kerb until the point is a sidewalk point (rounded kerb returns cut the corner)
    for (let d = 2.2; d <= 3.6 && !ok; d += 0.2) {
      const x = n.x + sx * ((n.hw || 11) + d), z = n.z + sz * ((n.hz || 5) + d * 0.9);
      if (isWalk(x, z) && inR(x, z, -WM)) ok = [x, z];
    }
    if (ok) { corners.set(cornerKey(n, sx, sz), P.length); P.push(ok); }
  }
}
const corner = (n, sx, sz) => corners.get(cornerKey(n, sx, sz));
const E = []; const seen = new Set();
const addEdge = (a, b, kind, axis, roadSide) => {
  if (a == null || b == null || a === b) return;
  const key = a < b ? a + ',' + b : b + ',' + a; if (seen.has(key)) return;
  const A = P[a], B = P[b], len = Math.hypot(B[0] - A[0], B[1] - A[1]);
  // validate the whole edge against the layout
  const n = Math.max(2, Math.ceil(len / 1.5));
  for (let i = 1; i < n; i++) {
    const x = A[0] + (B[0] - A[0]) * i / n, z = A[1] + (B[1] - A[1]) * i / n;
    if (kind === 0 ? !isWalk(x, z) : !isRoad(x, z)) return;
  }
  // side: +1 if the roadway lies to the RIGHT of A -> B (right = (-uz, ux) in the browser x, z frame), -1 if to the left; 0 for crosswalks
  let side = 0;
  if (roadSide) { const ux = (B[0] - A[0]) / len, uz = (B[1] - A[1]) / len; side = Math.sign((-uz) * roadSide[0] + ux * roadSide[1]) || 1; }
  seen.add(key); E.push({ a, b, kind, axis, len, side });
};
const at = new Map(nodes.map((n) => [n.j * R.nx + n.i, n]));
for (const n of nodes) {
  // along the avenue: south corners of (i, j) -> north corners of (i, j + 1)
  const m = at.get((n.j + 1) * R.nx + n.i);
  if (m && R.avSeg(n.i, n.j)) for (const sx of [-1, 1]) addEdge(corner(n, sx, 1), corner(m, sx, -1), 0, 0, [-sx, 0]);
  // along the street: east corners of (i, j) -> west corners of (i + 1, j)
  const q = at.get(n.j * R.nx + n.i + 1);
  if (q && R.stSeg(n.i, n.j)) for (const sz of [-1, 1]) addEdge(corner(n, 1, sz), corner(q, -1, sz), 0, 1, [0, -sz]);
  // crosswalks (only across existing legs)
  const leg = { N: n.j > 0 && R.avSeg(n.i, n.j - 1), S: R.avSeg(n.i, n.j), W: n.i > 0 && R.stSeg(n.i - 1, n.j), E: R.stSeg(n.i, n.j) };
  if (leg.N) addEdge(corner(n, -1, -1), corner(n, 1, -1), 1, 0);
  if (leg.S) addEdge(corner(n, -1, 1), corner(n, 1, 1), 1, 0);
  if (leg.W) addEdge(corner(n, -1, -1), corner(n, -1, 1), 1, 1);
  if (leg.E) addEdge(corner(n, 1, -1), corner(n, 1, 1), 1, 1);
}
// drop corners without edges, renumber
const used = new Set(); for (const e of E) { used.add(e.a); used.add(e.b); }
const remap = new Map(); const wl = ['# P6 city life pedestrian graph: generated by tools/life/export_lanes.mjs (do not edit)', `B ${rx0} ${rz0} ${rx1} ${rz1}`];
[...used].sort((a, b) => a - b).forEach((k, i) => { remap.set(k, i); wl.push(`P ${i} ${f(P[k][0])} ${f(P[k][1])}`); });
E.forEach((e, i) => wl.push(`E ${i} ${remap.get(e.a)} ${remap.get(e.b)} ${e.kind} ${e.axis} ${f(e.len)} ${e.side}`));
fs.writeFileSync(path.join(OUT, 'walk.txt'), wl.join('\n') + '\n');
console.log(`walk.txt: ${remap.size} corners, ${E.length} edges (${E.filter((e) => e.kind).length} crosswalks), sidewalk length ${f(E.filter((e) => !e.kind).reduce((s, e) => s + e.len, 0), 0)} m`);
