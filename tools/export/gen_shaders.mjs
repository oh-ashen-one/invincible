const texMacros = (list) => {
  const decl = list.map(([n, arr]) => `${arr ? 'Texture2DArray' : 'Texture2D'} ${n}, SamplerState ${n}Sampler`).join(', ');
  const pass = list.map(([n]) => `${n}, ${n}Sampler`).join(', ');
  return { decl, pass };
};
