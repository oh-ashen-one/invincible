// P6 City life: dump the browser road network (src/world/npc/roads.js buildRoads(), the SAME data the browser traffic and
// crowd use) for the Midtown 3x3 region as two small text files the Unreal build feeds to the life actors:
//   unreal/WebHomage/Scripts/life_data/lanes.txt   lane links + junction connectors + connector conflicts + signal nodes
//   unreal/WebHomage/Scripts/life_data/walk.txt    pedestrian graph: sidewalk corners, sidewalk edges, crosswalk edges
// Frame: browser metres (x east, z south). The Unreal side maps (x, z) -> UE (100 x, 100 z) cm (see docs/night1/city/EXPORT.md).
//
//   node tools/life/export_lanes.mjs [--region x0,z0,x1,z1]
//
// lanes.txt (one record per line, '#' comments):
//   N id x z hw hz sig                                node: centre, avenue / street half widths, signalised (avenue x street) 0/1
//   L id from to ax az dx dz len kind lane axis sig noPark narrow p0 p1 ..   link (lane centre line start, unit dir, length); kind 0 av 1 st 2 ws 3 diag;
//                                                    axis 0 av 1 st (signal phase axis); pN = parking side lateral offsets right of travel
//   C id fromLink toLink turn len n x0 z0 ... xN zN   connector through the junction box (n polyline points); turn 0 S 1 L 2 R
//   X id a b c ...                                   connector ids whose paths cross / merge with connector id (same node, other approach)
// Signal phases (props.js phase(), 40 s cycle) are compiled into the C++ (WHLifeTraffic.cpp), not exported.
//
// walk.txt:
//   P id x z                                          sidewalk corner point
//   E id a b kind axis len side                       edge a-b; kind 0 sidewalk 1 crosswalk; axis (crosswalks) 0 = crossed by avenue traffic, 1 = crossed by street traffic;
//                                                     side +1 / -1: the roadway lies to the right / left of a -> b (sidewalk edges), 0 crosswalk
//   B x0 z0 x1 z1                                     region bounds
//
// parked.txt (needs --layout <export>/layout.json for the curb props):
//   type x z yawDeg r g b flags                       parked car / curb taxi / double-parked truck / bus at its stop (type = index in the C++ order taxi, taxi_hy,
//                                                    taxi_mv, taxi_gr, sedan, hatch, sedan2, cross, suv, suv2, pickup, van, truck, bus, tour; colour linear; flags 1 = hazards)
