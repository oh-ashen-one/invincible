const R = buildRoads();
const inR = (x, z, m = 0) => x >= rx0 - m && x <= rx1 + m && z >= rz0 - m && z <= rz1 + m;
const f = (v, d = 2) => (+v.toFixed(d)).toString();

// ------------------------------------------------------------------ lanes
const links = R.links.filter((l) => inR(l.ax, l.az) && inR(l.ax + l.dx * l.len, l.az + l.dz * l.len) && !l.bridge && !l.vmap && l.len > 4);
const ids = new Set(links.map((l) => l.id));
const nodeIds = new Set();
for (const l of links) { nodeIds.add(l.from); nodeIds.add(l.to); }
const kindOf = (l) => (l.diag ? 3 : l.kind === 'ws' ? 2 : l.kind === 'st' ? 1 : 0);
const lines = ['# P6 city life lanes: generated by tools/life/export_lanes.mjs from src/world/npc/roads.js (do not edit)'];
for (const nid of [...nodeIds].sort((a, b) => a - b)) {
  const n = R.nodes[nid]; if (!n) continue;
  lines.push(`N ${n.id} ${f(n.x)} ${f(n.z)} ${f(n.hw || 0)} ${f(n.hz || 0)} ${n.av && n.st ? 1 : 0}`);
}
for (const l of links) {
  const sig = l.signal ? 1 : 0, axis = l.axis === 'st' ? 1 : 0;
  lines.push(`L ${l.id} ${l.from} ${l.to} ${f(l.ax)} ${f(l.az)} ${f(l.dx, 4)} ${f(l.dz, 4)} ${f(l.len)} ${kindOf(l)} ${l.lane || 0} ${axis} ${sig} ${l.noPark ? 1 : 0} ${l.narrow ? 1 : 0}` +
    (l.parkSides ? ' ' + l.parkSides.map((v) => f(v)).join(' ') : ''));
}
const conns = []; // {id, L, O, turn, P, len, poly}
let cid = 0;
for (const l of links) {
  for (const o of l.out || []) {
    if (!ids.has(o.link.id)) continue;
    const C = connector(l, o.link, o.turn);
    if (!C || !C.P) continue;
    const poly = [];
    const N = Math.max(4, Math.min(24, Math.ceil(C.len / 2.5)));
    for (let i = 0; i <= N; i++) { const t = i / N, u = 1 - t, P = C.P; poly.push([u * u * u * P[0] + 3 * u * u * t * P[2] + 3 * u * t * t * P[4] + t * t * t * P[6], u * u * u * P[1] + 3 * u * u * t * P[3] + 3 * u * t * t * P[5] + t * t * t * P[7]]); }
    let len = 0; for (let i = 1; i < poly.length; i++) len += Math.hypot(poly[i][0] - poly[i - 1][0], poly[i][1] - poly[i - 1][1]);
    conns.push({ id: cid++, L: l, O: o.link, turn: o.turn === 'S' ? 0 : o.turn === 'L' ? 1 : 2, poly, len });
  }
}
for (const c of conns) lines.push(`C ${c.id} ${c.L.id} ${c.O.id} ${c.turn} ${f(c.len)} ${c.poly.length} ${c.poly.map((p) => f(p[0]) + ' ' + f(p[1])).join(' ')}`);
// conflicts: connectors of the same node from DIFFERENT approach links whose paths come within 2.3 m (or that merge into one out link)
const byNode = new Map();
for (const c of conns) { const k = c.L.to; if (!byNode.has(k)) byNode.set(k, []); byNode.get(k).push(c); }
const dense = (poly) => { const o = []; for (let i = 1; i < poly.length; i++) { const a = poly[i - 1], b = poly[i], n = Math.max(1, Math.ceil(Math.hypot(b[0] - a[0], b[1] - a[1]) / 0.5)); for (let k = 0; k < n; k++) o.push([a[0] + (b[0] - a[0]) * k / n, a[1] + (b[1] - a[1]) * k / n]); } o.push(poly[poly.length - 1]); return o; };
let nconf = 0;
for (const cs of byNode.values()) {
  const D = cs.map((c) => dense(c.poly));
  for (let i = 0; i < cs.length; i++) {
    const conf = [];
    for (let j = 0; j < cs.length; j++) {
      if (i === j || cs[i].L === cs[j].L) continue;
      let hit = cs[i].O === cs[j].O;
      for (let a = 0; a < D[i].length && !hit; a++) for (let b = 0; b < D[j].length; b++) if (Math.hypot(D[i][a][0] - D[j][b][0], D[i][a][1] - D[j][b][1]) < 2.3) { hit = true; break; }
      if (hit) conf.push(cs[j].id);
    }
    if (conf.length) { lines.push(`X ${cs[i].id} ${conf.join(' ')}`); nconf += conf.length; }
  }
}
fs.writeFileSync(path.join(OUT, 'lanes.txt'), lines.join('\n') + '\n');
console.log(`lanes.txt: ${nodeIds.size} nodes, ${links.length} links, ${conns.length} connectors, ${nconf} conflict pairs`);


